import { spawnSync } from "node:child_process";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC_DIR = join(ROOT, "public");
const IGNORE_FILE = join(PUBLIC_DIR, ".assetsignore");
const BUCKET = "gamevault-unity-assets";
// Workers static assets must be 25 MiB or smaller.
const MAX_ASSET_BYTES = 25 * 1024 * 1024;

const shouldUpload =
  process.env.CI === "true" ||
  process.env.WORKERS_CI === "1" ||
  process.env.FORCE_R2_UPLOAD === "1";

function walk(dir, found = []) {
  for (const name of readdirSync(dir, { withFileTypes: true })) {
    if (name.name === ".assetsignore") continue;
    const full = join(dir, name.name);
    if (name.isDirectory()) walk(full, found);
    else if (name.isFile()) found.push(full);
  }
  return found;
}

function contentTypeFor(key) {
  if (/\.framework\.js\.unityweb$/i.test(key) || /\.js$/i.test(key)) {
    return "application/javascript";
  }
  if (/\.wasm\.unityweb$/i.test(key)) return "application/wasm";
  if (/\.json(\.unityweb)?$/i.test(key)) return "application/json";
  return "application/octet-stream";
}

function wrangler(args, { capture = false } = {}) {
  const bin = process.platform === "win32" ? "npx.cmd" : "npx";
  return spawnSync(bin, ["--yes", "wrangler", ...args], {
    cwd: ROOT,
    env: process.env,
    encoding: "utf8",
    stdio: capture ? ["ignore", "pipe", "pipe"] : "inherit",
    shell: process.platform === "win32",
  });
}

function writeIgnore(keys) {
  const lines = [
    "# Generated by scripts/prepare-large-assets.mjs",
    "# Workers cannot upload static assets larger than 25 MiB.",
    "# These files are uploaded to R2 and served by the Worker.",
    ...keys.map((key) => `/${key}`),
    "",
  ];
  writeFileSync(IGNORE_FILE, lines.join("\n"));
}

function ensureBucket() {
  const created = wrangler(["r2", "bucket", "create", BUCKET], { capture: true });
  const output = `${created.stdout || ""}\n${created.stderr || ""}`;
  if (created.status === 0) {
    console.log(`Created R2 bucket ${BUCKET}.`);
    return;
  }
  if (/already exists/i.test(output)) {
    console.log(`R2 bucket ${BUCKET} already exists.`);
    return;
  }
  process.stderr.write(output);
  process.exit(created.status || 1);
}

function upload(key, file) {
  const args = [
    "r2",
    "object",
    "put",
    `${BUCKET}/${key}`,
    `--file=${file}`,
    `--content-type=${contentTypeFor(key)}`,
    "--cache-control=public, max-age=31536000, immutable",
    "--remote",
    "--force",
  ];
  if (/\.unityweb$/i.test(key)) args.push("--content-encoding=gzip");

  const mib = (statSync(file).size / (1024 * 1024)).toFixed(1);
  console.log(`Uploading ${key} (${mib} MiB) to R2 bucket ${BUCKET}...`);
  const put = wrangler(args);
  if (put.status !== 0) process.exit(put.status || 1);
}

const large = walk(PUBLIC_DIR)
  .filter((file) => statSync(file).size > MAX_ASSET_BYTES)
  .map((file) => ({
    file,
    key: relative(PUBLIC_DIR, file).split("\\").join("/"),
  }))
  .sort((a, b) => a.key.localeCompare(b.key));

if (large.length === 0) {
  console.log("No static assets over 25 MiB.");
  if (shouldUpload) writeIgnore([]);
  process.exit(0);
}

writeIgnore(large.map((item) => item.key));
console.log(
  `Excluded from Workers assets:\n${large.map((item) => `  ${item.key}`).join("\n")}`
);

if (!shouldUpload) {
  console.log("Skipping R2 upload outside CI. Set FORCE_R2_UPLOAD=1 to upload.");
  process.exit(0);
}

ensureBucket();
for (const item of large) upload(item.key, item.file);
